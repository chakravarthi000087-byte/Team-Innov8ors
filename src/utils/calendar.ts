import { ExtractedTask } from '../types/actacite';

/**
 * Attempts to parse loose academic date strings into rough Date objects.
 * Supports patterns like "15th March 2026", "2026-03-15", "April 25, 2026", etc.
 */
function parseAcademicDate(dateStr: string | null): Date | null {
  if (!dateStr) return null;

  // Clean ordinal suffixes: 1st, 2nd, 3rd, 4th, etc.
  const cleaned = dateStr
    .replace(/(\d+)(st|nd|rd|th)/gi, '$1')
    .replace(/\s+by\s+/i, ' ')
    .replace(/\s+at\s+/i, ' ');

  // Try standard parsing
  const timestamp = Date.parse(cleaned);
  if (!isNaN(timestamp)) {
    return new Date(timestamp);
  }

  // Regex for DD Month YYYY
  const match = cleaned.match(/(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})/);
  if (match) {
    const months = [
      'jan', 'feb', 'mar', 'apr', 'may', 'jun',
      'jul', 'aug', 'sep', 'oct', 'nov', 'dec'
    ];
    const monthIndex = months.findIndex((m) =>
      match[2].toLowerCase().startsWith(m)
    );
    if (monthIndex !== -1) {
      const year = parseInt(match[3], 10);
      const day = parseInt(match[1], 10);
      return new Date(year, monthIndex, day, 17, 0, 0); // Default to 5:00 PM
    }
  }

  return null;
}

function formatICSDate(date: Date): string {
  const pad = (n: number) => (n < 10 ? `0${n}` : `${n}`);
  const y = date.getUTCFullYear();
  const m = pad(date.getUTCMonth() + 1);
  const d = pad(date.getUTCDate());
  const hh = pad(date.getUTCHours());
  const mm = pad(date.getUTCMinutes());
  const ss = pad(date.getUTCSeconds());
  return `${y}${m}${d}T${hh}${mm}${ss}Z`;
}

/**
 * Generates an iCalendar (.ics) string for tasks with deadlines.
 */
export function generateICS(tasks: ExtractedTask[], noticeTitle: string): string {
  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//ActaCite//Academic Notice Intelligence Engine//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:ActaCite - ${noticeTitle.replace(/[\\,;]/g, '')}`,
  ];

  const now = new Date();
  const nowStr = formatICSDate(now);

  let eventCount = 0;

  tasks.forEach((task, index) => {
    const eventDate = parseAcademicDate(task.resolvedDeadline || task.deadline);
    if (!eventDate) return;

    eventCount++;
    const uid = `actacite-${Date.now()}-${index}@actacite.internal`;
    const dtStart = formatICSDate(eventDate);
    // End time 1 hour later
    const dtEnd = formatICSDate(new Date(eventDate.getTime() + 60 * 60 * 1000));

    const docs = task.required_documents.length
      ? `\\n\\nRequired Documents:\\n- ${task.required_documents.join('\\n- ')}`
      : '';

    const reviewWarning = task.needs_review
      ? `\\n\\n[AMBIGUITY FLAG]: ${task.review_reason || 'Date/Instruction conflict detected'}`
      : '';

    const description = `TASK: ${task.task_description}\\n\\nELIGIBILITY: ${task.eligibility}\\n\\nSOURCE EVIDENCE (${task.evidence.page_reference}):\\n"${task.evidence.exact_quote}"${docs}${reviewWarning}\\n\\nGenerated by ActaCite AI Notice Intelligence.`;

    lines.push(
      'BEGIN:VEVENT',
      `UID:${uid}`,
      `DTSTAMP:${nowStr}`,
      `DTSTART:${dtStart}`,
      `DTEND:${dtEnd}`,
      `SUMMARY:[ActaCite] ${task.task_description.slice(0, 70)}`,
      `DESCRIPTION:${description}`,
      'STATUS:CONFIRMED',
      'BEGIN:VALARM',
      'TRIGGER:-P1D',
      'DESCRIPTION:Reminder 1 Day Before Deadline',
      'ACTION:DISPLAY',
      'END:VALARM',
      'END:VEVENT'
    );
  });

  lines.push('END:VCALENDAR');

  return lines.join('\r\n');
}

export function downloadICS(tasks: ExtractedTask[], noticeTitle: string) {
  const icsData = generateICS(tasks, noticeTitle);
  const blob = new Blob([icsData], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  const safeTitle = noticeTitle.replace(/[^a-z0-9]/gi, '_').toLowerCase();
  link.download = `actacite_${safeTitle || 'notice'}_deadlines.ics`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
